const fs = require('node:fs');
const path = require('node:path');
const babel = require('@babel/core');
const { Resvg } = require('@resvg/resvg-js');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'assets/subject-patterns');
const manifestPath = path.join(root, 'src/config/subjectPatternImages.android.js');
const check = process.argv.includes('--check');
const parse = filename => babel.parseSync(fs.readFileSync(filename, 'utf8'), {
  filename, configFile: false, babelrc: false,
  parserOpts: { plugins: ['jsx', 'typescript'] },
}).program.body;
const subjectNodes = parse(path.join(root, 'src/config/subjectIcons.js'));
const imports = new Map(subjectNodes.filter(node => node.type === 'ImportDeclaration')
  .flatMap(node => node.specifiers.map(specifier => [specifier.local.name, specifier.imported.name])));
const subjects = subjectNodes.find(node => node.declaration?.declarations?.[0]?.id.name === 'SUBJECT_ICONS')
  .declaration.declarations[0].init.properties;
const definitions = path.resolve(path.dirname(require.resolve('phosphor-react-native')), '../../src/defs');

const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
function svgMarkup(node) {
  if (node.type === 'JSXFragment') return node.children.map(svgMarkup).join('');
  if (node.type === 'JSXText') return node.value.trim();
  if (node.type !== 'JSXElement') throw new Error(`Unsupported icon node: ${node.type}`);
  const name = node.openingElement.name.name.toLowerCase();
  const attributes = node.openingElement.attributes.map(attribute => {
    if (attribute.type !== 'JSXAttribute') throw new Error('Unsupported icon attribute');
    const value = attribute.value.type === 'JSXExpressionContainer' ? attribute.value.expression.value : attribute.value.value;
    if (value === undefined) throw new Error('Icon attributes must be literal values');
    const key = attribute.name.name.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`);
    return `${key}="${escape(value)}"`;
  }).join(' ');
  return `<${name} ${attributes}>${node.children.map(svgMarkup).join('')}</${name}>`;
}

function write(filename, content) {
  const buffer = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (check) {
    if (!fs.existsSync(filename) || !fs.readFileSync(filename).equals(buffer)) {
      throw new Error(`Subject patterns are stale: ${path.relative(root, filename)}. Run npm run icons:generate.`);
    }
  } else {
    fs.mkdirSync(path.dirname(filename), { recursive: true });
    fs.writeFileSync(filename, buffer);
  }
}

const sources = [];
for (const subject of subjects) {
  const key = subject.key.name || subject.key.value;
  const iconName = imports.get(subject.value.name);
  const definition = parse(path.join(definitions, `${iconName}.tsx`))
    .find(node => node.type === 'ExportDefaultDeclaration').declaration;
  const regular = definition.arguments[0].elements.find(entry => entry.elements[0].value === 'regular');
  if (!regular) throw new Error(`Missing regular Phosphor icon: ${iconName}`);
  const shape = svgMarkup(regular.elements[1]);
  const instances = [[23, 19, -8], [69, 19, 8], [0, 57, 8], [46, 57, -8], [92, 57, 8]]
    .map(([x, y, angle]) => `<g transform="translate(${x} ${y}) rotate(${angle}) scale(${18 / 256}) translate(-128 -128)">${shape}</g>`).join('');
  for (const scale of [1, 2, 3]) {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${92 * scale}" height="${76 * scale}" viewBox="0 0 92 76" fill="black">${instances}</svg>`;
    const rendered = new Resvg(svg).render();
    if (!rendered.pixels.some((value, index) => index % 4 === 3 && value > 0)) {
      throw new Error(`Empty subject pattern: ${key}`);
    }
    write(path.join(output, `${key}${scale === 1 ? '' : `@${scale}x`}.png`), rendered.asPng());
  }
  sources.push(`  ${key}: require('../../assets/subject-patterns/${key}.png'),`);
}
write(manifestPath, `// Generated by npm run icons:generate from subjectIcons.js and Phosphor's regular paths.\nexport const SUBJECT_PATTERN_IMAGES = {\n${sources.join('\n')}\n};\n`);
write(path.join(output, 'LICENSE'), fs.readFileSync(path.join(definitions, '../../LICENSE')));
console.log(`${check ? 'Checked' : 'Generated'} ${sources.length} subject pattern tiles at 1x, 2x and 3x.`);
