const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const website = require('../src/config/website.cjs');

for (const origin of Object.values(website)) {
  const url = new URL(origin);
  assert.ok(url.protocol === 'https:' && url.origin === origin, 'Website URLs must be HTTPS origins without paths or credentials.');
}

const output = path.resolve(__dirname, '../functions/src/website.generated.cjs');
const source = '// Generated by scripts/sync-website-config.cjs from src/config/website.cjs.\n'
  + '// Do not edit manually. Firebase Functions deploys this configuration with its own package.\n'
  + `module.exports = ${JSON.stringify(website, null, 2)};\n`;

if (process.argv.includes('--check')) {
  assert.equal(fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '', source,
    'Functions website configuration is out of date. Run npm run config:sync.');
} else if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== source) {
  fs.writeFileSync(output, source);
}
